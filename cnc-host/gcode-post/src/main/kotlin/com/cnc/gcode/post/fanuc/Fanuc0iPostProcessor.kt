package com.cnc.gcode.post.fanuc

import com.cnc.gcode.post.GcodeProgram
import com.cnc.gcode.post.MachineFamily
import com.cnc.gcode.post.PostOptions
import com.cnc.gcode.post.PostProcessor
import com.cnc.model.cam.MotionType
import com.cnc.model.cam.Toolpath
import com.cnc.model.cam.ToolpathSegment

/**
 * FANUC 0i / 0-MA 两轴车床后处理器。
 *
 * 输出语法（Fanuc 0i-MF / 0i-TF 兼容）：
 *
 * ```
 * O1001 (PROGRAM NAME - CNC_HOST)
 * G21 G28 U0 V0 W0          ← 公制 + 可选回原点
 * G07 G90 G99 G54           ← 直径编码 + 绝对坐标 + mm/rev + 工件系
 * M03 S1200 T0101           ← 主轴正转 + 转速 + 刀号+刀补
 * M08                        ← 冷却液
 * G00 U-180.0 W20.0          ← 快速到起刀点（相对）
 * G01 U-20.0 W-30.0 F0.2     ← 直线切削 F=mm/rev
 * G02 U+10.0 W-5.0 I5.0 K-2.5 ← 顺时针圆弧切削
 * M05                        ← 主轴停
 * M09                        ← 冷却液关
 * M30                        ← 程序结束 + 复位
 * %
 * ```
 *
 * 注意：这里默认绝对坐标 (G90)，输出 X/Z 为绝对尺寸。
 * 若 PostOptions.absoluteMode = false → 增量 G91，输出 U/W。
 */
class Fanuc0iPostProcessor : PostProcessor {

    override val machineFamily: MachineFamily = MachineFamily.FANUC_0I

    override fun generate(toolpath: Toolpath, options: PostOptions): GcodeProgram {
        val out = mutableListOf<String>()

        // ===== 程序头 =====
        out += "O${options.programNumber} (${options.programName})"
        if (options.emitComments) {
            out += "(Generated by CNC_HOST gcode-post)"
            out += "(Source toolpath: ${toolpath.id})"
        }
        out += "%"  // Fanuc 程序开始标记

        // ===== 初始设定 =====
        val setup = mutableListOf<String>()
        setup += if (options.useMetric) "G21" else "G20"   // 单位
        setup += if (options.diameterMode) "G07" else "G08"  // 直径/半径
        setup += if (options.absoluteMode) "G90" else "G91"  // 绝对/增量
        setup += if (options.feedPerMinute) "G98" else "G99" // 进给单位
        setup += "G${options.workOffset}"                     // 工件系
        out += setup.joinToString(" ")

        if (options.homeOnStart) {
            // G28 回原点（U0 W0 = 通过当前点）
            out += "G28"
        }

        // ===== 刀具与主轴 =====
        val firstTool = toolpath.segments.firstOrNull()?.toolNumber ?: 1
        out += "T${"%02d".format(firstTool)}${"%02d".format(firstTool)}"
        val firstRpm = toolpath.segments.firstOrNull()?.spindleRpm?.takeIf { it > 0 } ?: 1200
        val m34 = if (options.spindleClockwise) "M03" else "M04"
        out += "$m34 S$firstRpm"

        if (options.autoCoolantOn) out += "M08"

        // ===== 运动段 =====
        var lineNum = options.lineNumberStep
        var lastMotionCode: String? = null
        var lastFeedMmPerRev: Double = -1.0
        var lastSpindleRpm: Int = -1

        for (seg in toolpath.segments) {
            val motionCode = when (seg.motionType) {
                MotionType.RAPID -> "G00"
                MotionType.LINEAR_FEED -> "G01"
                MotionType.ARC_FEED -> if (seg.clockwise == true) "G02" else "G03"
            }

            val xStr = formatCoord(seg.end.x, options)  // X = 直径值（G07 模式下）
            val zStr = formatCoord(seg.end.y, options)  // Z = 轴向

            val tokens = mutableListOf<String>()
            if (motionCode != lastMotionCode) tokens += motionCode
            tokens += "X$xStr"
            tokens += "Z$zStr"

            if (seg.motionType == MotionType.ARC_FEED) {
                // Fanuc 用 I/K：圆心相对起点
                val cx = seg.center?.x ?: continue
                val cz = seg.center?.y ?: continue
                val iStr = formatCoord(cx - seg.start.x, options)
                val kStr = formatCoord(cz - seg.start.y, options)
                tokens += "I$iStr"
                tokens += "K$kStr"
            }

            // 进给
            if (seg.motionType != MotionType.RAPID) {
                val feedValue = if (options.feedPerMinute) seg.feedMmPerMin
                                else seg.feedMmPerMin / maxOf(seg.spindleRpm, 1)
                // F0.2 风格（mm/rev，小数格式） vs F150.0（mm/min，整数/小数）
                val fStr = if (options.feedPerMinute) "F${formatCoord(feedValue, options)}"
                            else "F${formatCoord(feedValue, options)}"
                if (feedValue > 0 && kotlin.math.abs(feedValue - lastFeedMmPerRev) > 0.001) {
                    tokens += fStr
                    lastFeedMmPerRev = feedValue
                }
            }

            // 主轴（仅在 RPM 变化时重发）
            if (seg.spindleRpm > 0 && seg.spindleRpm != lastSpindleRpm) {
                val sm34 = if (options.spindleClockwise) "M03" else "M04"
                tokens += "$sm34 S${seg.spindleRpm}"
                lastSpindleRpm = seg.spindleRpm
            }

            // 输出行（带行号）
            val line = if (options.lineNumberStep > 0) {
                "N$lineNum " + tokens.joinToString(" ")
            } else {
                tokens.joinToString(" ")
            }
            out += line

            lastMotionCode = motionCode
            lineNum += options.lineNumberStep
        }

        // ===== 程序尾 =====
        if (options.autoCoolantOn) out += "M09"
        out += "M05"
        if (options.homeOnStart) out += "G28"
        out += if (options.useM30) "M30" else "M02"
        out += "%"

        return GcodeProgram(
            programNumber = options.programNumber,
            machineFamily = machineFamily,
            lines = out,
            sourceToolpathId = toolpath.id
        )
    }

    private fun formatCoord(value: Double, options: PostOptions): String {
        val dp = options.decimalPlaces
        return String.format("%.${dp}f", value)
    }
}
